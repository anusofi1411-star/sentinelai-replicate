/******************************************************************************
 * SentinelAI-X
 * File        : TimeManager.h
 * Module      : Time Manager
 * Description : Handles NTP based date, time and DAY/NIGHT detection
 ******************************************************************************/

#ifndef TIME_MANAGER_H
#define TIME_MANAGER_H


//==============================================================================
// Libraries
//==============================================================================

#include "common.h"

#include <WiFi.h>
#include <time.h>
#include <stdint.h>



//==============================================================================
// Time Manager Class
//==============================================================================

class TimeManager
{

public:


    //==========================================================================
    // Constructor
    //==========================================================================

    TimeManager();



    //==========================================================================
    // Initialize Time Manager
    //==========================================================================

    void begin();



    //==========================================================================
    // Sync Time From NTP Server
    //==========================================================================

    void syncTime();

    //==========================================================================
    // Manually Set Date & Time
    //==========================================================================

    void setDateTime(uint8_t day, uint8_t month, uint16_t year, uint8_t hour, uint8_t minute, uint8_t second);



    //==========================================================================
    // Update Current Time
    //==========================================================================

    void update();



    //==========================================================================
    // Get Time Mode
    //==========================================================================

    TimeMode getTimeMode() const;



    //==========================================================================
    // Get Time Values
    //==========================================================================

    uint8_t getHour() const;

    uint8_t getMinute() const;

    uint8_t getSecond() const;



    //==========================================================================
    // Get Date Values
    //==========================================================================

    uint8_t getDay() const;

    uint8_t getMonth() const;

    uint16_t getYear() const;



    //==========================================================================
    // Get Weekday
    //==========================================================================

    const char* getWeekday() const;



    //==========================================================================
    // Formatted Output
    //==========================================================================

    const char* getDateString() const;

    const char* getTimeString() const;



private:


    //==========================================================================
    // Current Time
    //==========================================================================

    uint8_t hour;

    uint8_t minute;

    uint8_t second;



    //==========================================================================
    // Current Date
    //==========================================================================

    uint8_t day;

    uint8_t month;

    uint16_t year;



    //==========================================================================
    // Weekday
    //==========================================================================

    char weekdayName[12];



    //==========================================================================
    // Day/Night Mode
    //==========================================================================

    TimeMode mode;



    //==========================================================================
    // Internal Buffers
    //==========================================================================

    mutable char dateBuffer[20];

    mutable char timeBuffer[20];



    //==========================================================================
    // Convert Weekday Number to Name
    //==========================================================================

    const char* getWeekdayName(int weekday);



};


#endif // TIME_MANAGER_H